"""
ДЗ презентации 2, базовый уровень, задача 2.
Время: 15–20 минут.

Тема: арифметические операторы.

Условие:
    Даны числа a = 7 и b = 3.
    Выведите их сумму, разность, произведение, частное,
    целочисленное деление, остаток и возведение в степень.
"""

def main():
    a = 7
    b = 3

    print("Сумма:", a + b)
    print("Разность:", a - b)
    print("Произведение:", a * b)
    print("Частное:", a / b)
    print("Целочисленное деление:", a // b)
    print("Остаток:", a % b)
    print("Возведение в степень:", a ** b)

if __name__ == "__main__":
    main()
