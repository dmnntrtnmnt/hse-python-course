"""
ДЗ презентации 4, базовый уровень, задача 2.
Время: 15–20 минут.

Тема: арифметика, форматирование.

Условие:
    Даны длина 12 и ширина 5 прямоугольника.
    Выведите площадь и периметр.
"""

def main():
    length = 12
    width = 5

    area = length * width
    perimeter = 2 * (length + width)

    print("Площадь:", area)
    print("Периметр:", perimeter)


if __name__ == "__main__":
    main()
